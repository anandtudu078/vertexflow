import type { FrontendCodeBlueprint } from '../types';
import { CodeIcon, LayersIcon } from './Icons';
import { Badge, Card, SectionHeading } from './ui';

function CodeBlock({ code }: { code: string }) {
  if (!code) return <p className="text-sm text-slate-500 italic">Not generated.</p>;
  return (
    <pre className="overflow-x-auto rounded-xl border border-slate-800/80 bg-black/40 p-4 font-mono text-[11px] leading-relaxed text-slate-300 whitespace-pre">
      {code}
    </pre>
  );
}

export function FrontendCodePanel({
  frontendCode,
}: {
  frontendCode: Partial<FrontendCodeBlueprint>;
}) {
  const styles = frontendCode.tailwind_styles_used ?? [];

  return (
    <Card>
      <SectionHeading
        icon={<LayersIcon />}
        title="Frontend worker output"
        hint="React + TypeScript component generated by the Frontend agent"
        action={
          frontendCode.component_name ? (
            <Badge tone="indigo">{frontendCode.component_name}</Badge>
          ) : undefined
        }
      />

      <div className="space-y-4">
        <div>
          <h3 className="mb-2 flex items-center gap-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
            <CodeIcon className="h-3.5 w-3.5" />
            React TSX component
          </h3>
          <CodeBlock code={frontendCode.react_tsx_code ?? ''} />
        </div>

        {frontendCode.state_management_summary ? (
          <div>
            <h3 className="mb-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
              State management
            </h3>
            <p className="text-sm leading-relaxed text-slate-300">
              {frontendCode.state_management_summary}
            </p>
          </div>
        ) : null}

        {styles.length > 0 ? (
          <div>
            <h3 className="mb-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
              Tailwind classes used
            </h3>
            <ul className="flex flex-wrap gap-1.5">
              {styles.map((cls) => (
                <li
                  key={cls}
                  className="rounded-lg border border-slate-800 bg-slate-900/60 px-2.5 py-1 font-mono text-[11px] text-indigo-300"
                >
                  {cls}
                </li>
              ))}
            </ul>
          </div>
        ) : null}
      </div>
    </Card>
  );
}
