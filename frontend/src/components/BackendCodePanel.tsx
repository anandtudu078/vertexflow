import type { BackendCodeBlueprint } from '../types';
import { CodeIcon, DatabaseIcon, PackageIcon } from './Icons';
import { Badge, Card, SectionHeading } from './ui';

function CodeBlock({ code }: { code: string }) {
  if (!code) return <p className="text-sm text-slate-500 italic">Not generated.</p>;
  return (
    <pre className="overflow-x-auto rounded-xl border border-slate-800/80 bg-black/40 p-4 font-mono text-[11px] leading-relaxed text-slate-300 whitespace-pre">
      {code}
    </pre>
  );
}

export function BackendCodePanel({
  backendCode,
}: {
  backendCode: Partial<BackendCodeBlueprint>;
}) {
  const deps = backendCode.dependencies_required ?? [];

  return (
    <Card>
      <SectionHeading
        icon={<CodeIcon />}
        title="Backend worker output"
        hint="FastAPI + SQLAlchemy code generated by the Backend agent"
        action={
          backendCode.module_name ? (
            <Badge tone="amber">{backendCode.module_name}</Badge>
          ) : undefined
        }
      />

      <div className="space-y-4">
        <div>
          <h3 className="mb-2 flex items-center gap-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
            <DatabaseIcon className="h-3.5 w-3.5" />
            Database models
          </h3>
          <CodeBlock code={backendCode.database_models_code ?? ''} />
        </div>

        <div>
          <h3 className="mb-2 flex items-center gap-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
            <CodeIcon className="h-3.5 w-3.5" />
            API endpoints
          </h3>
          <CodeBlock code={backendCode.api_endpoints_code ?? ''} />
        </div>

        {deps.length > 0 ? (
          <div>
            <h3 className="mb-2 flex items-center gap-2 text-[11px] font-semibold tracking-wider text-slate-400 uppercase">
              <PackageIcon className="h-3.5 w-3.5" />
              Dependencies
            </h3>
            <ul className="flex flex-wrap gap-1.5">
              {deps.map((dep) => (
                <li
                  key={dep}
                  className="rounded-lg border border-slate-800 bg-slate-900/60 px-2.5 py-1 font-mono text-[11px] text-slate-300"
                >
                  {dep}
                </li>
              ))}
            </ul>
          </div>
        ) : null}
      </div>
    </Card>
  );
}
